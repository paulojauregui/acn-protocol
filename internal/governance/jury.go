// Jury and Spark engine configuration constants.
//
// Pre-conditions: none (compile-time immutable constants).
// Post-conditions: defines default DGX Spark vLLM endpoints and timeout bounds (< 2.0s).
const (
	// DefaultSparkBaseURL is the Tailscale vLLM OpenAI-compatible endpoint on DGX Spark.
	DefaultSparkBaseURL = "http://happy.tail749110.ts.net:8000/v1/chat/completions"
	// DefaultSparkModel is the optimized quantized model running on the GB10 node.
	DefaultSparkModel = "nvidia/Qwen3.8-Flash-Next-FP4-Local"
	// DefaultJuryTimeout is the strict upper bound for jury arbitration requests.
	DefaultJuryTimeout = 1800 * time.Millisecond
)

// Dispute arbitration winner identifiers.
//
// Pre-conditions: none (compile-time constants).
// Post-conditions: defines valid resolution winners for dispute cases.
const (
	// WinnerUser denotes the dispute resolved in favor of the client user.
	WinnerUser = "USER"
	// WinnerVendor denotes the dispute resolved in favor of the service vendor.
	WinnerVendor = "VENDOR"
)

// Arbitration engine identifier constants.
//
// Pre-conditions: none (compile-time constants).
// Post-conditions: specifies which decision engine rendered the verdict rationale.
const (
	// EngineDGXSparkLLM indicates the rationale was generated by the remote DGX Spark LLM.
	EngineDGXSparkLLM = "DGX_SPARK_LLM"
	// EngineDeterministic indicates the verdict was computed via local multi-factor heuristics.
	EngineDeterministic = "DETERMINISTIC_MULTI_FACTOR"
)

// Sentinel errors returned by Jury operations.
//
// Pre-conditions: none (package-level immutable error values).
// Post-conditions: returned when input validation fails during dispute arbitration.
var (
	// ErrEmptyCaseID is returned when a dispute case identifier is blank.
	ErrEmptyCaseID = errors.New("governance: case id must not be empty")
	// ErrEmptyAppointmentID is returned when an appointment identifier is blank.
	ErrEmptyAppointmentID = errors.New("governance: appointment id must not be empty")
)

// DisputeCase represents the complete evidentiary record of a disputed appointment.
//
// Pre-conditions: CaseID and AppointmentID must be non-empty strings.
// Post-conditions: holds hardware beacon, POS receipts, and reputation metrics for arbitration.
type DisputeCase struct {
	CaseID              string  `json:"case_id"`
	AppointmentID       string  `json:"appointment_id"`
	UserDID             string  `json:"user_did"`
	VendorDID           string  `json:"vendor_did"`
	UserClaimPresent    bool    `json:"user_claim_present"`
	VendorClaimPresent  bool    `json:"vendor_claim_present"`
	StripePOSReceipt    bool    `json:"stripe_pos_receipt"`
	LocalBeaconVerified bool    `json:"local_beacon_verified"`
	UserReputation      float64 `json:"user_reputation"`
	VendorConflictCount int     `json:"vendor_conflict_count"`
}

// JuryVerdict is the binding resolution of an appointment dispute.
//
// Pre-conditions: Winner must be "USER" or "VENDOR"; EngineUsed must be a known engine constant.
// Post-conditions: specifies slashing directives and an evidentiary rationale.
type JuryVerdict struct {
	CaseID        string    `json:"case_id"`
	AppointmentID string    `json:"appointment_id"`
	Winner        string    `json:"winner"`
	SlashUser     bool      `json:"slash_user"`
	SlashVendor   bool      `json:"slash_vendor"`
	EngineUsed    string    `json:"engine_used"`
	Rationale     string    `json:"rationale"`
	DecidedAt     time.Time `json:"decided_at"`
}

// Jury arbitrates disputes using hybrid deterministic rules and optional DGX Spark LLM enrichment.
//
// Pre-conditions: initialized via NewJury.
// Post-conditions: concurrency-safe via sync.RWMutex; enforces < 2.0s bounded latency.
type Jury struct {
	mu              sync.RWMutex
	sparkURL        string
	model           string
	enableRemoteLLM bool
	httpClient      *http.Client
	verdicts        map[string]*JuryVerdict
}

// NewJury initializes a dispute arbitration jury with configured endpoint and timeout bounds.
//
// Pre-conditions: none; sparkURL defaults to DefaultSparkBaseURL if empty.
// Post-conditions: returns a Jury configured with DefaultJuryTimeout (< 2.0s) and empty verdict cache.
func NewJury(sparkURL string, enableRemoteLLM bool) *Jury {
	if sparkURL == "" {
		sparkURL = DefaultSparkBaseURL
	}
	return &Jury{
		sparkURL:        sparkURL,
		model:           DefaultSparkModel,
		enableRemoteLLM: enableRemoteLLM,
		httpClient: &http.Client{
			Timeout: DefaultJuryTimeout,
		},
		verdicts: make(map[string]*JuryVerdict),
	}
}

type openAIChatMessage struct {
	Role    string `json:"role"`
	Content string `json:"content"`
}

type openAIChatRequest struct {
	Model       string              `json:"model"`
	Messages    []openAIChatMessage `json:"messages"`
	MaxTokens   int                 `json:"max_tokens"`
	Temperature float64             `json:"temperature"`
}

type openAIChatChoice struct {
	Message openAIChatMessage `json:"message"`
}

type openAIChatResponse struct {
	Choices []openAIChatChoice `json:"choices"`
}

// ArbitrateDispute resolves an appointment dispute through deterministic evaluation and optional LLM audit.
//
// Pre-conditions: ctx must not be nil; c.CaseID and c.AppointmentID must not be empty.
// Post-conditions: returns a non-nil JuryVerdict with Winner, Slashing flags, and Rationale;
// falls back seamlessly to DETERMINISTIC_MULTI_FACTOR if remote LLM call fails or times out.
func (j *Jury) ArbitrateDispute(ctx context.Context, c DisputeCase) (*JuryVerdict, error) {
	if c.CaseID == "" {
		return nil, ErrEmptyCaseID
	}
	if c.AppointmentID == "" {
		return nil, ErrEmptyAppointmentID
	}

	var winner string
	var slashUser, slashVendor bool
	var rationale string

	if c.StripePOSReceipt && c.LocalBeaconVerified {
		winner = WinnerUser
		slashUser = false
		slashVendor = true
		rationale = "Hardware beacon and Stripe POS receipt verify user presence; vendor slashed."
	} else if (c.StripePOSReceipt || c.LocalBeaconVerified) && c.VendorConflictCount >= 2 {
		winner = WinnerUser
		slashUser = false
		slashVendor = true
		rationale = "Corroborated presence signal combined with repeated vendor conflicts (>=2); vendor slashed."
	} else if !c.StripePOSReceipt && !c.LocalBeaconVerified && !c.VendorClaimPresent {
		winner = WinnerVendor
		slashUser = true
		slashVendor = false
		rationale = "Absence of hardware beacon and POS receipt confirms failure of user presence; user slashed."
	} else if !c.StripePOSReceipt && !c.LocalBeaconVerified {
		winner = WinnerVendor
		slashUser = true
		slashVendor = false
		rationale = "Lack of objective beacon or POS proof fails user presence burden; user slashed."
	} else if c.UserReputation > 4.0 && c.VendorConflictCount > 0 {
		winner = WinnerUser
		slashUser = false
		slashVendor = true
		rationale = "High user reputation and vendor conflict history favor user."
	} else {
		winner = WinnerVendor
		slashUser = true
		slashVendor = false
		rationale = "Insufficient evidence to overturn vendor claim."
	}

	engineUsed := EngineDeterministic

	if j.enableRemoteLLM && j.sparkURL != "" {
		llmRationale, err := j.querySparkAudit(ctx, c, winner, slashUser, slashVendor)
		if err == nil && llmRationale != "" {
			rationale = llmRationale
			engineUsed = EngineDGXSparkLLM
		}
	}

	verdict := &JuryVerdict{
		CaseID:        c.CaseID,
		AppointmentID: c.AppointmentID,
		Winner:        winner,
		SlashUser:     slashUser,
		SlashVendor:   slashVendor,
		EngineUsed:    engineUsed,
		Rationale:     rationale,
		DecidedAt:     time.Now().UTC(),
	}

	j.mu.Lock()
	j.verdicts[c.CaseID] = verdict
	j.mu.Unlock()

	clone := *verdict
	return &clone, nil
}

// GetVerdict retrieves a previously arbitrated verdict by CaseID.
//
// Pre-conditions: none.
// Post-conditions: returns a deep copy of the verdict and true if found, or nil and false otherwise.
func (j *Jury) GetVerdict(caseID string) (*JuryVerdict, bool) {
	j.mu.RLock()
	defer j.mu.RUnlock()

	v, exists := j.verdicts[caseID]
	if !exists {
		return nil, false
	}
	clone := *v
	return &clone, true
}

func (j *Jury) querySparkAudit(ctx context.Context, c DisputeCase, winner string, slashUser, slashVendor bool) (string, error) {
	reqCtx, cancel := context.WithTimeout(ctx, DefaultJuryTimeout)
	defer cancel()

	userPrompt := fmt.Sprintf(
		"CaseID: %s, AppointmentID: %s, UserDID: %s, VendorDID: %s, BeaconVerified: %t, StripeReceipt: %t, VendorConflicts: %d, Verdict: %s, SlashUser: %t, SlashVendor: %t. Provide concise audit rationale.",
		c.CaseID, c.AppointmentID, c.UserDID, c.VendorDID, c.LocalBeaconVerified, c.StripePOSReceipt, c.VendorConflictCount, winner, slashUser, slashVendor,
	)

	reqPayload := openAIChatRequest{
		Model: j.model,
		Messages: []openAIChatMessage{
			{
				Role:    "system",
				Content: "You are the ACN Protocol AI Audit Jury running on DGX Spark. Analyze the dispute evidence and provide a concise, binding audit rationale.",
			},
			{
				Role:    "user",
				Content: userPrompt,
			},
		},
		MaxTokens:   150,
		Temperature: 0.2,
	}

	bodyBytes, err := json.Marshal(reqPayload)
	if err != nil {
		return "", err
	}

	httpReq, err := http.NewRequestWithContext(reqCtx, http.MethodPost, j.sparkURL, bytes.NewReader(bodyBytes))
	if err != nil {
		return "", err
	}
	httpReq.Header.Set("Content-Type", "application/json")

	resp, err := j.httpClient.Do(httpReq)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("spark http error: status code %d", resp.StatusCode)
	}

	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", err
	}

	var chatResp openAIChatResponse
	if err := json.Unmarshal(respBody, &chatResp); err != nil {
		return "", err
	}

	if len(chatResp.Choices) == 0 {
		return "", errors.New("empty choices in spark response")
	}

	content := strings.TrimSpace(chatResp.Choices[0].Message.Content)
	if content == "" {
		return "", errors.New("empty content in spark response choice")
	}

	return content, nil
}
